function getProperty(object, propertyName) {
  return object.properties.find((candidate) => {
    if (!ts.isPropertyAssignment(candidate)) {
      return false;
    }
    const name = candidate.name;
    return (
      (ts.isIdentifier(name) || ts.isStringLiteral(name)) &&
      name.text === propertyName
    );
  });
}

function getStringProperty(object, propertyName, required = true) {
  const property = getProperty(object, propertyName);
  if (!property) {
    if (required) {
      throw new Error(`Missing string property: ${propertyName}`);
    }
    return null;
  }
  if (!ts.isPropertyAssignment(property) || !ts.isStringLiteral(property.initializer)) {
    throw new Error(`Invalid string property: ${propertyName}`);
  }
  return property.initializer.text;
}

function getStringArrayProperty(object, propertyName) {
  const property = getProperty(object, propertyName);
  if (
    !property ||
    !ts.isPropertyAssignment(property) ||
    !ts.isArrayLiteralExpression(property.initializer)
  ) {
    throw new Error(`Invalid string array property: ${propertyName}`);
  }
  return property.initializer.elements.map((element) => {
    if (!ts.isStringLiteral(element)) {
      throw new Error(`Invalid array value in: ${propertyName}`);
    }
    return element.text;
  });
}

function parseExerciseRecords(source, filePath, generated) {
  const sourceFile = ts.createSourceFile(
    filePath,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const records = [];

  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const idProperty = getProperty(node, 'id');
      if (idProperty) {
        const id = getStringProperty(node, 'id');
        const inferredChestRecord = !getProperty(node, 'primaryBodyPartId');
        records.push({
          id,
          name: getStringProperty(node, 'name'),
          targetBodyArea: inferredChestRecord
            ? 'Chest / upper body'
            : getStringProperty(node, 'targetBodyArea'),
          category: inferredChestRecord
            ? 'Strength'
            : getStringProperty(node, 'category'),
          primaryBodyPartId: inferredChestRecord
            ? 'chest'
            : getStringProperty(node, 'primaryBodyPartId'),
          secondaryBodyPartIds: getStringArrayProperty(
            node,
            'secondaryBodyPartIds',
          ),
          difficulty: getStringProperty(node, 'difficulty'),
          equipmentIds: getStringArrayProperty(node, 'equipmentIds'),
          description: getStringProperty(node, 'description'),
          instructions: getStringArrayProperty(node, 'instructions'),
          progressionExerciseId:
            getStringProperty(node, 'progressionExerciseId', false) ?? undefined,
          regressionExerciseId:
            getStringProperty(node, 'regressionExerciseId', false) ?? undefined,
          thumbnail: {
            source: generated ? 'placeholder' : 'preserved',
            alt:
              id === 'bodyweight-squat'
                ? 'Abstract illustration of a person performing a bodyweight squat'
                : id === 'push-up'
                  ? 'Abstract illustration of a person performing a push-up'
                  : `Placeholder exercise illustration for ${getStringProperty(node, 'name')}`,
          },
          video:
            id === 'push-up'
              ? null
              : {
                  uri: DEVELOPMENT_VIDEO_URL,
                  label: DEVELOPMENT_VIDEO_LABEL,
                  accessibilityLabel: `Non-exercise development playback sample for ${getStringProperty(node, 'name')}`,
                },
          generated,
        });
      }
    }
    ts.forEachChild(node, visit);
  }

  visit(sourceFile);
  return records;
}

function executeCommonJs(source, filePath, requireModule = () => ({})) {
  const output = ts.transpileModule(source, {
    compilerOptions: {
      jsx: ts.JsxEmit.ReactJSX,
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: filePath,
  }).outputText;
  const module = { exports: {} };
  const run = new Function(
    'require',
    'module',
    'exports',
    '__filename',
    '__dirname',
    output,
  );
  run(requireModule, module, module.exports, filePath, path.dirname(filePath));
  return module.exports;
}

function resolveTypeScriptModule(basePath) {
  for (const candidate of [basePath, `${basePath}.ts`, `${basePath}.tsx`]) {
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  throw new Error(`Unable to resolve TypeScript module: ${basePath}`);
}

function loadTypeScriptModule(filePath, cache = new Map()) {
  if (cache.has(filePath)) {
    return cache.get(filePath).exports;
  }

  const module = { exports: {} };
  cache.set(filePath, module);
  const source = readFileSync(filePath, 'utf8');
  const output = ts.transpileModule(source, {
    compilerOptions: {
      jsx: ts.JsxEmit.ReactJSX,
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: filePath,
  }).outputText;
  const requireModule = (request) => {
    if (request.startsWith('@/')) {
      return loadTypeScriptModule(
        resolveTypeScriptModule(path.join(ROOT_DIR, 'src', request.slice(2))),
        cache,
      );
    }
    if (request.startsWith('.')) {
      const resolvedPath = path.resolve(path.dirname(filePath), request);
      if (path.extname(resolvedPath) === '.png') {
        return resolvedPath;
      }
      return loadTypeScriptModule(resolveTypeScriptModule(resolvedPath), cache);
    }
    return requireNodeModule(request);
  };
  const run = new Function(
    'require',
    'module',
    'exports',
    '__filename',
    '__dirname',
    output,
  );
  run(requireModule, module, module.exports, filePath, path.dirname(filePath));
  return module.exports;
}

function expectThrow(action, expectedMessage) {
  assert.throws(action, (error) => {
    assert.match(error.message, expectedMessage);
    return true;
  });
}

async function expectReject(action, expectedMessage) {
  await assert.rejects(action, (error) => {
    assert.match(error.message, expectedMessage);
    return true;
  });
}

