function createNativeComponent(tagName) {
  return function NativeComponent({
    accessibilityHint,
    accessibilityLabel,
    accessibilityLiveRegion,
    accessibilityRole,
    children,
  }) {
    return React.createElement(
      tagName,
      {
        'aria-label': accessibilityLabel,
        'aria-description': accessibilityHint,
        'aria-live': accessibilityLiveRegion,
        role: accessibilityRole === 'summary' ? 'status' : accessibilityRole,
      },
      children,
    );
  };
}

function createComponentRequire(typesExports, exerciseVideoExports, videoStatus = 'readyToPlay') {
  const View = createNativeComponent('div');
  const Pressable = createNativeComponent('button');
  const Text = createNativeComponent('span');
  const Image = ({ accessibilityLabel }) =>
    React.createElement('img', { alt: accessibilityLabel });
  const ThemedText = ({ children, ...props }) =>
    React.createElement(Text, props, children);
  const ThemedView = ({ children, ...props }) =>
    React.createElement(View, props, children);

  return (request) => {
    if (request === 'react' || request === 'react/jsx-runtime') {
      return requireNodeModule(request);
    }
    if (request === 'react-native') {
      return {
        ActivityIndicator: createNativeComponent('span'),
        Platform: { select: (values) => values.default },
        Pressable,
        StyleSheet: { absoluteFill: {}, create: (styles) => styles },
        Text,
        View,
      };
    }
    if (request === 'expo-image') {
      return { Image };
    }
    if (request === 'expo-video') {
      return {
        useVideoPlayer: () => ({ status: videoStatus }),
        VideoView: ({ accessibilityLabel, nativeControls }) =>
          React.createElement('video', {
            'aria-label': accessibilityLabel,
            controls: nativeControls,
          }),
      };
    }
    if (request === 'expo') {
      return { useEvent: () => ({ status: videoStatus }) };
    }
    if (request.endsWith('/exercise-types')) {
      return typesExports;
    }
    if (request.endsWith('/exercise-video')) {
      return exerciseVideoExports;
    }
    if (request.endsWith('/themed-text')) {
      return { ThemedText };
    }
    if (request.endsWith('/themed-view')) {
      return { ThemedView };
    }
    if (request.endsWith('/section-screen')) {
      return {
        SectionScreen: ({ children, description, title }) =>
          React.createElement(
            'main',
            null,
            React.createElement('h1', null, title),
            React.createElement('p', null, description),
            children,
          ),
      };
    }
    if (request.endsWith('/constants/theme')) {
      return {
        Spacing: {
          half: 2,
          one: 4,
          two: 8,
          three: 16,
          four: 24,
          five: 32,
          six: 64,
        },
      };
    }
    if (request.endsWith('/use-theme')) {
      return {
        useTheme: () => ({
          accent: '#000',
          background: '#fff',
          backgroundElement: '#eee',
          backgroundSelected: '#ddd',
          border: '#ccc',
          text: '#000',
          textSecondary: '#333',
        }),
      };
    }
    return {};
  };
}

async function verifyRepresentativeRendering(records, typesExports) {
  const videoPath = path.join(
    ROOT_DIR,
    'src/components/exercises/exercise-video.tsx',
  );
  const cardPath = path.join(
    ROOT_DIR,
    'src/components/exercises/exercise-card.tsx',
  );
  const detailPath = path.join(
    ROOT_DIR,
    'src/components/exercises/exercise-detail.tsx',
  );
  const [videoSource, cardSource, detailSource] = await Promise.all([
    readFile(videoPath, 'utf8'),
    readFile(cardPath, 'utf8'),
    readFile(detailPath, 'utf8'),
  ]);

  const readyVideoExports = executeCommonJs(
    videoSource,
    videoPath,
    createComponentRequire(typesExports, null),
  );
  const componentRequire = createComponentRequire(
    typesExports,
    readyVideoExports,
  );
  const { ExerciseCard } = executeCommonJs(cardSource, cardPath, componentRequire);
  const { ExerciseDetail } = executeCommonJs(
    detailSource,
    detailPath,
    componentRequire,
  );

  const representativesByEquipment = new Map();
  for (const record of records) {
    for (const equipmentId of record.equipmentIds) {
      if (!representativesByEquipment.has(equipmentId)) {
        representativesByEquipment.set(equipmentId, record);
      }
    }
  }
  assert.equal(representativesByEquipment.size, 20);

  for (const [equipmentId, record] of representativesByEquipment) {
    const equipmentLabel = typesExports.formatExerciseEquipment(
      record.equipmentIds,
    );
    const cardMarkup = renderToStaticMarkup(
      React.createElement(ExerciseCard, { exercise: record, onPress: () => {} }),
    );
    const detailMarkup = renderToStaticMarkup(
      React.createElement(ExerciseDetail, { exercise: record }),
    );
    for (const value of [
      record.name,
      record.description,
      record.targetBodyArea,
      equipmentLabel,
    ]) {
      assert.ok(cardMarkup.includes(value), `Card omitted ${value} for ${equipmentId}`);
      assert.ok(detailMarkup.includes(value), `Detail omitted ${value} for ${equipmentId}`);
    }
    assert.ok(cardMarkup.includes(`Open ${record.name}.`));
    assert.ok(cardMarkup.includes(record.thumbnail.alt));
    assert.ok(detailMarkup.includes(record.instructions[0]));
    assert.ok(detailMarkup.includes(DEVELOPMENT_VIDEO_LABEL));
    assert.ok(detailMarkup.includes(record.video.accessibilityLabel));
  }

  const pushUp = records.find((record) => record.id === 'push-up');
  const unavailableMarkup = renderToStaticMarkup(
    React.createElement(ExerciseDetail, { exercise: pushUp }),
  );
  assert.ok(unavailableMarkup.includes('Video unavailable'));
  assert.ok(unavailableMarkup.includes('Bodyweight / no equipment'));

  for (const [status, expectedText] of [
    ['loading', 'Loading video'],
    ['error', 'Playback unavailable'],
  ]) {
    const videoExports = executeCommonJs(
      videoSource,
      videoPath,
      createComponentRequire(typesExports, null, status),
    );
    const markup = renderToStaticMarkup(
      React.createElement(videoExports.ExerciseVideo, {
        exerciseName: records[1].name,
        thumbnail: records[1].thumbnail,
        video: records.find((record) => record.id === 'burpee').video,
      }),
    );
    assert.ok(markup.includes(expectedText));
    if (status === 'error') {
      assert.ok(markup.includes('Retry video'));
    }
  }

  assert.ok(!videoSource.includes('.play('));
  assert.ok(videoSource.includes('nativeControls'));
  assert.ok(videoSource.includes('playsInline'));
  assert.ok(videoSource.includes('fullscreenOptions={{ enable: true }}'));
}

async function readFinalRecords() {
  const catalogSource = await readFile(CATALOG_PATH, 'utf8');
  const preservedRecords = parseExerciseRecords(
    catalogSource,
    CATALOG_PATH,
    false,
  );
  const generatedFileNames = (await readdir(GENERATED_DIR))
    .filter((fileName) => /^exercise-catalog-\d{3}\.generated\.ts$/.test(fileName))
    .sort();
  const generatedRecords = [];

  for (const fileName of generatedFileNames) {
    const filePath = path.join(GENERATED_DIR, fileName);
    const source = await readFile(filePath, 'utf8');
    assert.ok(source.startsWith(GENERATED_HEADER), `${fileName} lacks generated header`);
    generatedRecords.push(...parseExerciseRecords(source, filePath, true));
  }

  const indexSource = await readFile(
    path.join(GENERATED_DIR, 'exercise-catalog.generated.ts'),
    'utf8',
  );
  assert.ok(indexSource.startsWith(GENERATED_HEADER), 'Generated index lacks header');
  return { catalogSource, generatedFileNames, records: [...preservedRecords, ...generatedRecords] };
}

async function verifyGenerationFailureCases(manifest, preservedIds, content) {
  const firstId = manifest.exercises.find(
    (exercise) => !preservedIds.includes(exercise.id),
  ).id;

  const missingContent = new Map(content);
  missingContent.delete(firstId);
  expectThrow(
    () => buildGeneratedOutputs(manifest, preservedIds, missingContent),
    /Missing authored content key/,
  );

  const extraContent = new Map(content);
  extraContent.set('not-a-manifest-exercise', {
    description: 'Not accepted.',
    instructions: ['Not accepted.'],
  });
  expectThrow(
    () => buildGeneratedOutputs(manifest, preservedIds, extraContent),
    /Extra authored content key/,
  );

  const emptyDescription = new Map(content);
  emptyDescription.set(firstId, {
    ...emptyDescription.get(firstId),
    description: ' ',
  });
  expectThrow(
    () => buildGeneratedOutputs(manifest, preservedIds, emptyDescription),
    /Empty authored description/,
  );

  const emptyInstructions = new Map(content);
  emptyInstructions.set(firstId, {
    ...emptyInstructions.get(firstId),
    instructions: [],
  });
  expectThrow(
    () => buildGeneratedOutputs(manifest, preservedIds, emptyInstructions),
    /Empty authored instruction list/,
  );

  const duplicateIdManifest = cloneManifest(manifest);
  duplicateIdManifest.exercises[1].id = duplicateIdManifest.exercises[0].id;
  expectThrow(
    () => buildGeneratedOutputs(duplicateIdManifest, preservedIds, content),
    /Duplicate manifest exercise ID/,
  );

  const duplicateNameManifest = cloneManifest(manifest);
  duplicateNameManifest.exercises[1].name = duplicateNameManifest.exercises[0].name;
  expectThrow(
    () => buildGeneratedOutputs(duplicateNameManifest, preservedIds, content),
    /Duplicate manifest exercise name/,
  );

  const duplicatePropertyDirectory = await mkdtemp(
    path.join(os.tmpdir(), 'oscar-exercise-content-'),
  );
  try {
    await writeFile(
      path.join(duplicatePropertyDirectory, 'duplicate.json'),
      '{"example":{"description":"one","description":"two","instructions":["step"]}}\n',
      'utf8',
    );
    await expectReject(
      readAuthoredContent(duplicatePropertyDirectory),
      /Duplicate authored content property/,
    );
  } finally {
    await rm(duplicatePropertyDirectory, { recursive: true, force: true });
  }
}

async function verifyStaleOutputChecks(outputs) {
  const temporaryDirectory = await mkdtemp(
    path.join(os.tmpdir(), 'oscar-exercise-catalog-'),
  );
  try {
    for (const [fileName, source] of outputs) {
      await writeFile(path.join(temporaryDirectory, fileName), source, 'utf8');
    }
    await checkGeneratedOutputs(outputs, temporaryDirectory);

    const firstFileName = outputs.keys().next().value;
    const firstPath = path.join(temporaryDirectory, firstFileName);
    const expectedSource = outputs.get(firstFileName);
    await writeFile(firstPath, `${expectedSource}// stale\n`, 'utf8');
    await expectReject(
      checkGeneratedOutputs(outputs, temporaryDirectory),
      /Generated output is stale/,
    );
    assert.equal(await readFile(firstPath, 'utf8'), `${expectedSource}// stale\n`);
    await writeFile(firstPath, expectedSource, 'utf8');

    await unlink(firstPath);
    await expectReject(
      checkGeneratedOutputs(outputs, temporaryDirectory),
      /Generated file set is stale/,
    );
    await writeFile(firstPath, expectedSource, 'utf8');

    const extraPath = path.join(
      temporaryDirectory,
      'exercise-catalog-old.generated.ts',
    );
    await writeFile(extraPath, GENERATED_HEADER, 'utf8');
    await expectReject(
      checkGeneratedOutputs(outputs, temporaryDirectory),
      /Generated file set is stale/,
    );
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
}

async function main() {
  const { manifest, preservedIds, content } = await loadGeneratorInputs();
  const firstBuild = buildGeneratedOutputs(manifest, preservedIds, content);
  const secondBuild = buildGeneratedOutputs(manifest, preservedIds, content);
  assert.deepEqual([...firstBuild.outputs], [...secondBuild.outputs]);
  await checkGeneratedOutputs(firstBuild.outputs);
  await verifyGenerationFailureCases(manifest, preservedIds, content);
  await verifyStaleOutputChecks(firstBuild.outputs);

  const {
    catalogSource,
    generatedFileNames,
    records: parsedRecords,
  } = await readFinalRecords();
  const { LOCAL_EXERCISES: records } = loadTypeScriptModule(CATALOG_PATH);
  assert.equal(parsedRecords.length, 216);
  assert.equal(parsedRecords.filter((record) => record.generated).length, 195);
  assert.equal(records.length, 216);
  assert.deepEqual(
    records.map((record) => record.id),
    parsedRecords.map((record) => record.id),
  );
  assert.deepEqual(
    records.slice(0, 21).map((record) => record.id),
    preservedIds,
  );

  const ids = records.map((record) => record.id);
  const names = records.map((record) => record.name);
  assert.equal(new Set(ids).size, 216);
  assert.equal(new Set(names).size, 216);
  assert.deepEqual(new Set(ids), new Set(manifest.exercises.map((exercise) => exercise.id)));

  const recordsById = new Map(records.map((record) => [record.id, record]));
  for (const exercise of manifest.exercises) {
    const record = recordsById.get(exercise.id);
    assert.ok(record, `Missing catalog record: ${exercise.id}`);
    assert.deepEqual(
      {
        id: record.id,
        name: record.name,
        primary: record.primaryBodyPartId,
        secondary: record.secondaryBodyPartIds,
        difficulty: record.difficulty,
        equipment: record.equipmentIds,
        progression: record.progressionExerciseId ?? null,
        regression: record.regressionExerciseId ?? null,
      },
      exercise,
      `Manifest parity failed: ${exercise.id}`,
    );
    assert.ok(record.description.trim(), `Empty description: ${exercise.id}`);
    assert.ok(record.instructions.length > 0, `Empty instructions: ${exercise.id}`);
  }

  const difficultyCounts = Object.groupBy(
    records,
    (record) => record.difficulty,
  );
  assert.equal(difficultyCounts.beginner.length, 100);
  assert.equal(difficultyCounts.intermediate.length, 97);
  assert.equal(difficultyCounts.advanced.length, 19);

  const bodyAreaCounts = Object.groupBy(
    records,
    (record) => record.targetBodyArea,
  );
  assert.equal(bodyAreaCounts['Lower body'].length, 43);
  assert.equal(bodyAreaCounts['Chest / upper body'].length, 116);
  assert.equal(bodyAreaCounts.Core.length, 35);
  assert.equal(bodyAreaCounts['Full body'].length, 22);
  assert.ok(records.every((record) => record.category === 'Strength'));

  const relationships = records.flatMap((record) =>
    [record.progressionExerciseId, record.regressionExerciseId].filter(Boolean),
  );
  assert.equal(relationships.length, 29);
  for (const record of records) {
    for (const relatedId of [
      record.progressionExerciseId,
      record.regressionExerciseId,
    ]) {
      if (relatedId) {
        assert.notEqual(relatedId, record.id);
        assert.ok(recordsById.has(relatedId));
      }
    }
  }

  const generatedSupportSource = await readFile(GENERATED_SUPPORT_PATH, 'utf8');
  assert.match(
    generatedSupportSource,
    /assets\/images\/exercises\/push-up\.png/,
  );
  assert.ok(generatedSupportSource.includes(DEVELOPMENT_VIDEO_URL));
  assert.ok(generatedSupportSource.includes(DEVELOPMENT_VIDEO_LABEL));
  assert.match(
    generatedSupportSource,
    /Placeholder exercise illustration for \$\{input\.name\}/,
  );
  assert.match(
    generatedSupportSource,
    /Non-exercise development playback sample for \$\{input\.name\}/,
  );
  assert.equal(records.filter((record) => record.video === null).length, 1);
  assert.equal(records.find((record) => record.video === null).id, 'push-up');

  const typesSource = await readFile(TYPES_PATH, 'utf8');
  const typesExports = executeCommonJs(typesSource, TYPES_PATH);
  const { defineExerciseCatalog } = typesExports;
  assert.equal(defineExerciseCatalog(records), records);
  const fixture = records[0];
  expectThrow(
    () => defineExerciseCatalog([fixture, { ...fixture }]),
    /Duplicate exercise ID/,
  );
  expectThrow(
    () =>
      defineExerciseCatalog([
        fixture,
        { ...records[1], name: fixture.name },
      ]),
    /Duplicate exercise name/,
  );
  expectThrow(
    () =>
      defineExerciseCatalog([
        { ...fixture, secondaryBodyPartIds: ['glutes', 'glutes'] },
      ]),
    /Duplicate secondary body part/,
  );
  expectThrow(
    () =>
      defineExerciseCatalog([
        { ...fixture, secondaryBodyPartIds: [fixture.primaryBodyPartId] },
      ]),
    /Primary body part repeated as secondary/,
  );
  expectThrow(
    () => defineExerciseCatalog([{ ...fixture, equipmentIds: ['bodyweight', 'bodyweight'] }]),
    /Duplicate equipment/,
  );
  expectThrow(
    () => defineExerciseCatalog([{ ...fixture, progressionExerciseId: fixture.id }]),
    /cannot reference itself/,
  );
  expectThrow(
    () => defineExerciseCatalog([{ ...fixture, progressionExerciseId: 'unknown-id' }]),
    /Related exercise ID not found/,
  );

  const filterSource = await readFile(FILTER_PATH, 'utf8');
  const { filterExercises } = executeCommonJs(filterSource, FILTER_PATH);
  const allFilters = { searchText: '', bodyArea: 'All', difficulty: 'All' };
  assert.equal(filterExercises(records, allFilters).length, 216);
  assert.equal(
    filterExercises(records, { ...allFilters, bodyArea: 'Lower body' }).length,
    43,
  );
  assert.equal(
    filterExercises(records, {
      ...allFilters,
      bodyArea: 'Chest / upper body',
    }).length,
    116,
  );
  for (const [difficulty, count] of [
    ['beginner', 100],
    ['intermediate', 97],
    ['advanced', 19],
  ]) {
    assert.equal(
      filterExercises(records, { ...allFilters, difficulty }).length,
      count,
    );
  }

  const representativeSearches = {
    chest: ['bench press', 'barbell-bench-press'],
    back: ['lat pulldown', 'seated-lat-pulldown'],
    quadriceps: ['goblet squat', 'goblet-squat'],
    hamstrings: ['leg curl', 'seated-leg-curl'],
    glutes: ['hip thrust', 'hip-thrust'],
    shoulders: ['lateral raise', 'dumbbell-lateral-raise'],
    biceps: ['biceps curl', 'dumbbell-biceps-curl'],
    triceps: ['triceps pushdown', 'cable-triceps-pushdown'],
    forearms: ['wrist curl', 'dumbbell-wrist-curl'],
    core: ['front plank', 'front-plank'],
    calves: ['calf raise', 'standing-calf-raise'],
    'full-body': ['burpee', 'burpee'],
  };
  for (const [primaryBodyPartId, [searchText, expectedId]] of Object.entries(
    representativeSearches,
  )) {
    const matches = filterExercises(records, { ...allFilters, searchText });
    assert.ok(matches.some((record) => record.id === expectedId));
    assert.equal(recordsById.get(expectedId).primaryBodyPartId, primaryBodyPartId);
  }
  assert.deepEqual(filterExercises(records, { ...allFilters, searchText: '  BuRpEe  ' }).map(({ id }) => id), ['burpee']);
  assert.equal(
    filterExercises(records, {
      searchText: 'squat',
      bodyArea: 'Lower body',
      difficulty: 'beginner',
    }).every(
      (record) =>
        record.targetBodyArea === 'Lower body' &&
        record.difficulty === 'beginner' &&
        record.name.toLocaleLowerCase().includes('squat'),
    ),
    true,
  );

  const repositorySource = await readFile(REPOSITORY_PATH, 'utf8');
  const repositoryExports = executeCommonJs(
    repositorySource,
    REPOSITORY_PATH,
    (request) => {
      if (request.endsWith('/exercise-catalog')) {
        return { LOCAL_EXERCISES: records };
      }
      return {};
    },
  );
  const repository = repositoryExports.localExerciseRepository;
  const listPromise = repository.listExercises();
  assert.ok(listPromise instanceof Promise);
  assert.equal(await listPromise, records);
  for (const record of records) {
    assert.equal(await repository.getExerciseById(record.id), record);
  }
  assert.equal(await repository.getExerciseById('unknown-exercise'), null);
  assert.equal(await repository.getExerciseById('BURPEE'), null);

  const routeSource = await readFile(ROUTE_PATH, 'utf8');
  const routeExports = executeCommonJs(routeSource, ROUTE_PATH, (request) => {
    if (request.endsWith('/exercise-repository')) {
      return repositoryExports;
    }
    if (request === 'react/jsx-runtime') {
      return { Fragment: Symbol('Fragment'), jsx: () => null, jsxs: () => null };
    }
    return {};
  });
  const staticParams = await routeExports.generateStaticParams();
  assert.deepEqual(
    staticParams,
    records.map((record) => ({ exerciseId: record.id })),
  );

  const usedEquipmentIds = new Set(records.flatMap((record) => record.equipmentIds));
  assert.equal(usedEquipmentIds.size, 20);
  assert.ok(
    records.every(
      (record) =>
        record.thumbnail.alt &&
        record.description &&
        record.instructions.length > 0 &&
        (record.video === null ||
          (record.video.uri === DEVELOPMENT_VIDEO_URL &&
            record.video.label === DEVELOPMENT_VIDEO_LABEL &&
            record.video.accessibilityLabel.includes(record.name))),
    ),
  );

  assert.equal(generatedFileNames.length, 8);
  assert.ok(catalogSource.includes('...GENERATED_EXERCISES'));
  assert.ok(catalogSource.includes("progressionExerciseId: 'goblet-squat'"));
  await verifyRepresentativeRendering(records, typesExports);

  console.log('Exercise catalog verification passed.');
  console.log(
    JSON.stringify(
      {
        catalogCount: records.length,
        generatedCount: parsedRecords.filter((record) => record.generated).length,
        difficultyCounts: Object.fromEntries(
          Object.entries(difficultyCounts).map(([key, value]) => [key, value.length]),
        ),
        bodyAreaCounts: Object.fromEntries(
          Object.entries(bodyAreaCounts).map(([key, value]) => [key, value.length]),
        ),
        relationshipFields: relationships.length,
        equipmentCategories: usedEquipmentIds.size,
        staticParams: staticParams.length,
      },
      null,
      2,
    ),
  );
}

