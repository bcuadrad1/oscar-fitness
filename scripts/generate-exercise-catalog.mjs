function fail(message) {
  throw new Error(message);
}

function assertUnique(values, label) {
  const seen = new Set();
  for (const value of values) {
    if (seen.has(value)) {
      fail(`Duplicate ${label}: ${value}`);
    }
    seen.add(value);
  }
}

function getObjectStringProperty(object, propertyName) {
  const property = object.properties.find(
    (candidate) =>
      ts.isPropertyAssignment(candidate) &&
      ts.isIdentifier(candidate.name) &&
      candidate.name.text === propertyName,
  );

  if (
    !property ||
    !ts.isPropertyAssignment(property) ||
    !ts.isStringLiteral(property.initializer)
  ) {
    return null;
  }

  return property.initializer.text;
}

export function extractPreservedExerciseIds(source) {
  const sourceFile = ts.createSourceFile(
    CATALOG_PATH,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const exerciseIds = [];

  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const id = getObjectStringProperty(node, 'id');
      if (id) {
        exerciseIds.push(id);
      }
    }
    ts.forEachChild(node, visit);
  }

  visit(sourceFile);
  assertUnique(exerciseIds, 'preserved exercise ID');
  return exerciseIds;
}

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, 'utf8'));
}

function assertNoDuplicateObjectKeys(node, filePath) {
  if (ts.isObjectLiteralExpression(node)) {
    const keys = [];
    for (const property of node.properties) {
      if (!ts.isPropertyAssignment(property)) {
        fail(`Invalid authored content property: ${filePath}`);
      }
      const key =
        ts.isStringLiteral(property.name) || ts.isIdentifier(property.name)
          ? property.name.text
          : null;
      if (!key) {
        fail(`Invalid authored content key: ${filePath}`);
      }
      keys.push(key);
      assertNoDuplicateObjectKeys(property.initializer, filePath);
    }
    assertUnique(keys, `authored content property in ${path.basename(filePath)}`);
    return;
  }

  if (ts.isArrayLiteralExpression(node)) {
    for (const element of node.elements) {
      assertNoDuplicateObjectKeys(element, filePath);
    }
  }
}

function assertNoDuplicateJsonKeys(source, filePath) {
  const sourceFile = ts.parseJsonText(filePath, source);
  if (sourceFile.parseDiagnostics.length > 0) {
    fail(`Invalid authored content JSON: ${filePath}`);
  }

  const statement = sourceFile.statements[0];
  const object =
    statement && ts.isExpressionStatement(statement) ? statement.expression : null;
  if (!object || !ts.isObjectLiteralExpression(object)) {
    fail(`Authored content must be a JSON object: ${filePath}`);
  }
  assertNoDuplicateObjectKeys(object, filePath);
}

export async function readAuthoredContent(contentDir = CONTENT_DIR) {
  const fileNames = (await readdir(contentDir))
    .filter((fileName) => fileName.endsWith('.json'))
    .sort();
  const content = new Map();

  for (const fileName of fileNames) {
    const filePath = path.join(contentDir, fileName);
    const source = await readFile(filePath, 'utf8');
    assertNoDuplicateJsonKeys(source, filePath);
    const entries = Object.entries(JSON.parse(source));
    for (const [id, value] of entries) {
      if (content.has(id)) {
        fail(`Duplicate authored content key: ${id}`);
      }
      content.set(id, value);
    }
  }

  return content;
}

function validateManifest(manifest) {
  if (!manifest || !Array.isArray(manifest.exercises)) {
    fail('Manifest must contain an exercises array.');
  }
  if (manifest.exercises.length !== EXPECTED_MANIFEST_COUNT) {
    fail(
      `Expected ${EXPECTED_MANIFEST_COUNT} manifest exercises, received ${manifest.exercises.length}.`,
    );
  }

  assertUnique(
    manifest.exercises.map((exercise) => exercise.id),
    'manifest exercise ID',
  );
  assertUnique(
    manifest.exercises.map((exercise) => exercise.name),
    'manifest exercise name',
  );

  const manifestIds = new Set(manifest.exercises.map((exercise) => exercise.id));
  for (const exercise of manifest.exercises) {
    if (
      !exercise ||
      typeof exercise !== 'object' ||
      typeof exercise.id !== 'string' ||
      exercise.id === '' ||
      typeof exercise.name !== 'string' ||
      exercise.name === '' ||
      !Array.isArray(exercise.secondary) ||
      !Array.isArray(exercise.equipment) ||
      (exercise.progression !== null && typeof exercise.progression !== 'string') ||
      (exercise.regression !== null && typeof exercise.regression !== 'string')
    ) {
      fail('Manifest exercise has an invalid field shape.');
    }
    if (!APPROVED_BODY_PART_IDS.has(exercise.primary)) {
      fail(`Unsupported primary body part for ${exercise.id}: ${exercise.primary}`);
    }
    assertUnique(exercise.secondary, `secondary body part for ${exercise.id}`);
    for (const secondaryBodyPartId of exercise.secondary) {
      if (!APPROVED_BODY_PART_IDS.has(secondaryBodyPartId)) {
        fail(
          `Unsupported secondary body part for ${exercise.id}: ${secondaryBodyPartId}`,
        );
      }
    }
    if (exercise.secondary.includes(exercise.primary)) {
      fail(`Primary body part repeated as secondary for ${exercise.id}`);
    }
    if (!APPROVED_DIFFICULTIES.has(exercise.difficulty)) {
      fail(`Unsupported difficulty for ${exercise.id}: ${exercise.difficulty}`);
    }
    if (exercise.equipment.length === 0) {
      fail(`Exercise must declare equipment: ${exercise.id}`);
    }
    assertUnique(exercise.equipment, `equipment for ${exercise.id}`);
    for (const equipmentId of exercise.equipment) {
      if (!APPROVED_EQUIPMENT_IDS.has(equipmentId)) {
        fail(`Unsupported equipment for ${exercise.id}: ${equipmentId}`);
      }
    }
    for (const relatedId of [exercise.progression, exercise.regression]) {
      if (relatedId !== null && !manifestIds.has(relatedId)) {
        fail(`Unknown manifest relationship for ${exercise.id}: ${relatedId}`);
      }
      if (relatedId === exercise.id) {
        fail(`Self relationship in manifest: ${exercise.id}`);
      }
    }
  }
}

function validateAuthoredContent(missingExercises, content) {
  const missingIds = new Set(missingExercises.map((exercise) => exercise.id));

  for (const id of missingIds) {
    if (!content.has(id)) {
      fail(`Missing authored content key: ${id}`);
    }
  }
  for (const id of content.keys()) {
    if (!missingIds.has(id)) {
      fail(`Extra authored content key: ${id}`);
    }
  }

  for (const exercise of missingExercises) {
    const entry = content.get(exercise.id);
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      fail(`Invalid authored content entry: ${exercise.id}`);
    }
    if (typeof entry.description !== 'string' || entry.description.trim() === '') {
      fail(`Empty authored description: ${exercise.id}`);
    }
    if (!Array.isArray(entry.instructions) || entry.instructions.length === 0) {
      fail(`Empty authored instruction list: ${exercise.id}`);
    }
    for (const instruction of entry.instructions) {
      if (typeof instruction !== 'string' || instruction.trim() === '') {
        fail(`Empty authored instruction step: ${exercise.id}`);
      }
    }
    const unexpectedKeys = Object.keys(entry).filter(
      (key) => key !== 'description' && key !== 'instructions',
    );
    if (unexpectedKeys.length > 0) {
      fail(`Unexpected authored content field for ${exercise.id}: ${unexpectedKeys[0]}`);
    }
  }
}

function getTargetBodyArea(primaryBodyPartId) {
  if (LOWER_BODY_PART_IDS.has(primaryBodyPartId)) {
    return 'Lower body';
  }
  if (UPPER_BODY_PART_IDS.has(primaryBodyPartId)) {
    return 'Chest / upper body';
  }
  if (primaryBodyPartId === 'core') {
    return 'Core';
  }
  if (primaryBodyPartId === 'full-body') {
    return 'Full body';
  }
  fail(`No target body area mapping for: ${primaryBodyPartId}`);
}

function renderArray(values) {
  return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

function renderExercise(exercise, content) {
  const lines = [
    '  createGeneratedExercise({',
    `    id: ${JSON.stringify(exercise.id)},`,
    `    name: ${JSON.stringify(exercise.name)},`,
    `    targetBodyArea: ${JSON.stringify(getTargetBodyArea(exercise.primary))},`,
    '    category: "Strength",',
    `    primaryBodyPartId: ${JSON.stringify(exercise.primary)},`,
    `    secondaryBodyPartIds: ${renderArray(exercise.secondary)},`,
    `    difficulty: ${JSON.stringify(exercise.difficulty)},`,
    `    equipmentIds: ${renderArray(exercise.equipment)},`,
    `    description: ${JSON.stringify(content.description)},`,
    '    instructions: [',
    ...content.instructions.map(
      (instruction) => `      ${JSON.stringify(instruction)},`,
    ),
    '    ],',
  ];

  if (exercise.progression !== null) {
    lines.push(
      `    progressionExerciseId: ${JSON.stringify(exercise.progression)},`,
    );
  }
  if (exercise.regression !== null) {
    lines.push(
      `    regressionExerciseId: ${JSON.stringify(exercise.regression)},`,
    );
  }
  lines.push('  }),');
  return lines.join('\n');
}

function renderChunk(exercises, chunkNumber, content) {
  const suffix = String(chunkNumber).padStart(3, '0');
  return `${GENERATED_HEADER}
import { createGeneratedExercise } from '../exercise-catalog-generated-support';

export const GENERATED_EXERCISES_${suffix} = [
${exercises.map((exercise) => renderExercise(exercise, content.get(exercise.id))).join('\n')}
] as const;
`;
}

function renderIndex(chunkCount) {
  const imports = [];
  const spreads = [];
  for (let index = 1; index <= chunkCount; index += 1) {
    const suffix = String(index).padStart(3, '0');
    imports.push(
      `import { GENERATED_EXERCISES_${suffix} } from './exercise-catalog-${suffix}.generated';`,
    );
    spreads.push(`  ...GENERATED_EXERCISES_${suffix},`);
  }

  return `${GENERATED_HEADER}
import type { Exercise } from '../exercise-types';
${imports.join('\n')}

export const GENERATED_EXERCISES = [
${spreads.join('\n')}
] as const satisfies readonly Exercise[];
`;
}

export function buildGeneratedOutputs(manifest, preservedIds, content) {
  validateManifest(manifest);
  if (
    preservedIds.length !== EXPECTED_PRESERVED_COUNT ||
    JSON.stringify(preservedIds) !== JSON.stringify(EXPECTED_PRESERVED_IDS)
  ) {
    fail(
      `Preserved exercise IDs or order differ from the approved ${EXPECTED_PRESERVED_COUNT}-record baseline.`,
    );
  }

  const manifestIds = new Set(manifest.exercises.map((exercise) => exercise.id));
  for (const id of preservedIds) {
    if (!manifestIds.has(id)) {
      fail(`Preserved exercise is outside the manifest: ${id}`);
    }
  }

  const preservedIdSet = new Set(preservedIds);
  const missingExercises = manifest.exercises.filter(
    (exercise) => !preservedIdSet.has(exercise.id),
  );
  if (missingExercises.length !== EXPECTED_GENERATED_COUNT) {
    fail(
      `Expected ${EXPECTED_GENERATED_COUNT} missing exercises, received ${missingExercises.length}.`,
    );
  }
  validateAuthoredContent(missingExercises, content);

  const outputs = new Map();
  for (let index = 0; index < missingExercises.length; index += CHUNK_SIZE) {
    const chunkNumber = index / CHUNK_SIZE + 1;
    const suffix = String(chunkNumber).padStart(3, '0');
    outputs.set(
      `exercise-catalog-${suffix}.generated.ts`,
      renderChunk(
        missingExercises.slice(index, index + CHUNK_SIZE),
        chunkNumber,
        content,
      ),
    );
  }
  outputs.set('exercise-catalog.generated.ts', renderIndex(outputs.size));

  return { missingExercises, outputs };
}

export async function loadGeneratorInputs() {
  const [manifest, catalogSource, content] = await Promise.all([
    readJson(MANIFEST_PATH),
    readFile(CATALOG_PATH, 'utf8'),
    readAuthoredContent(),
  ]);
  const preservedIds = extractPreservedExerciseIds(catalogSource);
  return { manifest, preservedIds, content };
}

export async function checkGeneratedOutputs(outputs, generatedDir = GENERATED_DIR) {
  let actualFileNames = [];
  try {
    actualFileNames = (await readdir(generatedDir))
      .filter((fileName) => GENERATED_FILE_PATTERN.test(fileName))
      .sort();
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw error;
    }
  }

  const expectedFileNames = [...outputs.keys()].sort();
  if (JSON.stringify(actualFileNames) !== JSON.stringify(expectedFileNames)) {
    fail(
      `Generated file set is stale. Expected ${expectedFileNames.join(', ')}, received ${actualFileNames.join(', ') || 'none'}.`,
    );
  }

  for (const [fileName, expected] of outputs) {
    const actual = await readFile(path.join(generatedDir, fileName), 'utf8');
    if (actual !== expected) {
      fail(`Generated output is stale: ${fileName}`);
    }
  }
}

async function writeOutputs(outputs) {
  await mkdir(GENERATED_DIR, { recursive: true });
  const expectedFileNames = new Set(outputs.keys());
  const actualFileNames = (await readdir(GENERATED_DIR)).filter((fileName) =>
    GENERATED_FILE_PATTERN.test(fileName),
  );

  await Promise.all(
    actualFileNames
      .filter((fileName) => !expectedFileNames.has(fileName))
      .map((fileName) => unlink(path.join(GENERATED_DIR, fileName))),
  );
  await Promise.all(
    [...outputs].map(([fileName, source]) =>
      writeFile(path.join(GENERATED_DIR, fileName), source, 'utf8'),
    ),
  );
}

async function main() {
  const check = process.argv.slice(2).includes('--check');
  const unknownArguments = process.argv
    .slice(2)
    .filter((argument) => argument !== '--check');
  if (unknownArguments.length > 0) {
    fail(`Unknown argument: ${unknownArguments[0]}`);
  }

  const { manifest, preservedIds, content } = await loadGeneratorInputs();
  const { missingExercises, outputs } = buildGeneratedOutputs(
    manifest,
    preservedIds,
    content,
  );

  if (check) {
    await checkGeneratedOutputs(outputs);
    console.log(`Generated exercise catalog is current (${missingExercises.length} records).`);
    return;
  }

  await writeOutputs(outputs);
  console.log(
    `Generated ${missingExercises.length} exercise records across ${outputs.size} files.`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
